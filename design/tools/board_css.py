"""Capture the CSS of the design canvas's Screens boards into a markdown inventory.

The canvas boards (claude.ai/artifact/TuTh7izChf3Dk74gvBvi7P, files at project/<Board>.dc.html)
style almost everything inline. This reads every Screens board, keeps the shared stylesheet,
counts each distinct inline style and each state style written in a board's script, and the
colours used, and writes design/board-css-inventory.md. design/screens-css.md names the
components; this file is the evidence behind it.

Usage: python3 design/tools/board_css.py <folder with project/*.dc.html and project/canvas.json> [version]
Download the boards first (Claude Code: Artifact read with paths project/<Board>.dc.html).
"""
import collections
import html
import json
import os
import re
import sys

SRC = sys.argv[1]
VERSION = sys.argv[2] if len(sys.argv) > 2 else 'unknown'
P = os.path.join(SRC, 'project')
OUT = os.path.join(os.path.dirname(__file__), '..', 'board-css-inventory.md')

canvas = json.load(open(os.path.join(P, 'canvas.json')))
order = sorted(canvas['boards'].items(), key=lambda kv: (kv[1].get('y', 0), kv[1].get('x', 0)))
screens = [k[:-8] for k, v in order if v.get('page') in (None, 'screens') and k not in ('DesignSystem.dc.html', 'Spool.dc.html')]
titles = {k[:-8]: v.get('title', '') for k, v in canvas['boards'].items()}
boards = [b for b in screens if os.path.exists(os.path.join(P, b + '.dc.html'))]


def norm(s):
    return '; '.join(d.strip() for d in s.strip().rstrip(';').split(';') if d.strip())


sheets = collections.Counter()
extra = {}
inline = collections.defaultdict(list)
scripted = collections.defaultdict(set)
colours = collections.Counter()
colour_boards = collections.defaultdict(set)

for b in boards:
    s = open(os.path.join(P, b + '.dc.html')).read()
    styles = [x.strip() for x in re.findall(r'<style>(.*?)</style>', s, re.S)]
    if styles:
        sheets[styles[0]] += 1
        if len(styles) > 1:
            extra[b] = styles[1:]
    body = s[s.find('<x-dc>'):s.find('</x-dc>')]
    for m in re.finditer(r'<(\w+)([^>]*?)\sstyle="([^"]*)"([^>]*)>([^<]{0,40})', body):
        tag, pre, st, post, txt = m.groups()
        if '{{' in st:
            continue
        cls = re.search(r'class="([^"]*)"', pre + post)
        inline[norm(st)].append((b, tag, cls.group(1) if cls else '', html.unescape(txt.strip())))
    script = s[s.find('class Component'):] if 'class Component' in s else ''
    for m in re.finditer(r"'([^']*?:[^']*?;[^']*?)'", script):
        v = m.group(1)
        if re.search(r'(border|background|font|padding|min-height|display|width|box-shadow)', v):
            scripted[norm(v)].add(b)
    stripped = s
    for x in styles[:1]:
        stripped = stripped.replace(x, '')
    for h in re.findall(r'#[0-9A-Fa-f]{6}\b|rgba?\([^)]*\)', stripped):
        colours[h.upper()] += 1
        colour_boards[h.upper()].add(b)

lines = [
    '# Board CSS inventory (generated)',
    '',
    f'Generated by `design/tools/board_css.py` from canvas version `{VERSION}`: {len(boards)} Screens boards. '
    'Do not edit by hand; rerun the script. The named components are in `design/screens-css.md`.',
    '',
    '## Boards',
    '',
    '| Board | Title |',
    '| --- | --- |',
] + [f'| {b} | {titles.get(b, "")} |' for b in boards]

lines += ['', '## Shared stylesheets', '']
for i, (sheet, n) in enumerate(sheets.most_common()):
    lines += [f'### Variant {i + 1}, used by {n} board(s)', '', '```css', sheet, '```', '']

lines += ['## Extra stylesheets on single boards', '']
for b, xs in extra.items():
    for x in xs:
        lines += [f'**{b}**', '', '```css', x, '```', '']

lines += ['## Colours (outside the shared stylesheet)', '', '| Colour | Uses | Boards |', '| --- | --- | --- |']
lines += [f'| `{h}` | {n} | {len(colour_boards[h])} |' for h, n in colours.most_common()]

lines += ['', '## Inline styles, most used first', '',
          'Each entry: how many elements, on how many boards, an example element and its text, then the declarations.', '']
for st, uses in sorted(inline.items(), key=lambda kv: (-len(kv[1]), kv[0])):
    bs = sorted(set(u[0] for u in uses))
    tag, cls, txt = uses[0][1], uses[0][2], uses[0][3]
    where = ', '.join(bs[:6]) + (f' +{len(bs) - 6}' if len(bs) > 6 else '')
    lines += [f'- **{len(uses)}× on {len(bs)}** `<{tag}{" class=" + cls if cls else ""}>` "{txt[:40]}" ({where})', f'  `{st}`']

lines += ['', '## State styles written in board scripts', '',
          'Styles a board switches at runtime (selected chip, done check, switch track…).', '']
for st, bs in sorted(scripted.items(), key=lambda kv: (-len(kv[1]), kv[0])):
    lines += [f'- **{len(bs)} board(s)** ({", ".join(sorted(bs))})', f'  `{st}`']

open(OUT, 'w').write('\n'.join(lines) + '\n')
print('wrote', os.path.normpath(OUT), '·', len(boards), 'boards ·', len(inline), 'inline styles ·', len(scripted), 'state styles')
