const [,, pw, url, out] = process.argv; const { chromium } = require(pw);
(async () => { const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1280, height: 1000 }, deviceScaleFactor: 1 });
 const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
 await p.goto(url, { waitUntil: 'networkidle' }); await p.waitForTimeout(600);
 await p.click('[data-sc="rows"]'); await p.waitForTimeout(500);
 const shot = async n => (await p.$('#phone')).screenshot({ path: out + '/' + n + '.png' });
 await shot('f1');
 await p.click('[data-list="2"]'); await p.waitForTimeout(400);
 await shot('f2');
 await p.click('#newList'); await p.waitForTimeout(400); await shot('f3');
 console.log(await p.$$eval('[data-list]', bs => bs.map(b => b.textContent + (b.getAttribute('aria-pressed') === 'true' ? '*' : ''))));
 console.log('errors', errs); await b.close(); })();
